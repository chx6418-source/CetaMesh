// DSH owns this stdio process; enforce the same persisted switches without requiring
// a separate Core-managed MCP instance to be running. Callback guards below remain active.
function registerTool(name, ...definition) {
  const handler = definition.pop();
  return server.tool(name, ...definition, async (...args) => {
    try {
      assertMcpToolEnabled('snowluma', name);
    } catch (error) {
      return { isError: true, content: [{ type: 'text', text: String(error.code || 'TOOL_DISABLED') + ': ' + error.message }] };
    }
    return handler(...args);
  });
}

