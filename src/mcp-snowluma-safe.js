function getAccess() {
  const c = getConfig();
  return {
    allowGroups: (c.allow?.groups ?? []).map(String),
    allowPrivate: (c.allow?.private ?? []).map(String),
    denyGroups: (c.deny?.groups ?? []).map(String),
    denyPrivate: (c.deny?.private ?? []).map(String),
    allowAllWhenEmpty: c.allowAllWhenEmpty === true
  };
}

function getOneBotConfig() {
  const c = getConfig();
  return {
    httpUrl: (c.snowluma?.httpUrl ?? 'http://127.0.0.1:3000').replace(/\/+$/, ''),
    token: c.snowluma?.httpAccessToken ?? c.snowluma?.accessToken ?? ''
  };
}

// 与 bridge.allowed 保持一致：allow 列表为空时按 allowAllWhenEmpty 放行
function isAllowed(allowList, denyList, id, allowAllWhenEmpty) {
  const s = String(id);
  if (denyList.includes(s)) return false;
  if (allowList.length > 0) return allowList.includes(s);
  return allowAllWhenEmpty;
}

// 防止底层网关把文本中的 [CQ: 当作 CQ 码解析：替换为全角冒号。
function escapeCqText(text) {
  return String(text ?? '').replace(/\[CQ:/gi, '[CQ：');
}

// 兼容模型把单条消息序列化成 JSON 字符串的情况，例如 "\"你好\"" → "你好"。
function unquoteJsonString(value) {
  if (typeof value !== 'string') return value;
  const t = value.trim();
  if (t.startsWith('"')) {
    try {
      const parsed = JSON.parse(t);
      if (typeof parsed === 'string') return parsed;
    } catch {}
  }
  return value;
}

// 构造可选的“引用/回复”消息段：
// - 传了 replyToMessageId 时，在文本前追加 reply 段，让 QQ 显示“引用了某条消息”；
// - 使用结构化消息段而不是 CQ 码，避免注入；
// - replyToMessageId 必须是非零整数（字符串数字也接受；QQ 消息 id 可能为负数）。
function messageSegments(message, replyToMessageId) {
  const segments = [];
  const replyId = replyToMessageId !== undefined && replyToMessageId !== null && String(replyToMessageId).trim() !== ''
    ? String(replyToMessageId).trim()
    : null;
  if (replyId !== null) {
    if (!/^-?[1-9]\d*$/.test(replyId)) {
      throw new Error('replyToMessageId 必须是非零整数（消息 id 可能为负数）');
    }
    segments.push({ type: 'reply', data: { id: replyId } });
  }
  segments.push({ type: 'text', data: { text: escapeCqText(String(message ?? '')) } });
  return segments;
}

async function onebot(action, params = {}) {
  const { httpUrl, token } = getOneBotConfig();
  const res = await fetch(`${httpUrl}/${action}`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) },
    body: JSON.stringify(params),
    signal: AbortSignal.timeout(15000)
  });
  if (!res.ok) {
    const hint = res.status === 426 ? '；HTTP 426 通常表示 httpUrl 指向了 WebSocket 端口，请检查 config.json 的 snowluma.httpUrl 是否为 OneBot HTTP API 地址' : '';
    throw new Error(`HTTP ${res.status}${hint}`);
  }
  const body = await res.json();
  if (body.status !== 'ok' || body.retcode !== 0) {
    throw new Error(`OneBot ${action} 失败: retcode=${body.retcode} ${body.wording ?? ''}`);
  }
  return body.data;
}

// 桥接数据面访问（D1-003）：二代仿真模式的状态工具都通过这里读写桥接内存态。
// 传输是 named pipe 数据面 IPC（src/control/data-ipc.js），不再是 loopback HTTP——
// release worker 不监听 127.0.0.1，MCP 经 worker 的 data.call 分派到达同一套
// 数据面路由与鉴权闸门。
// 桥接访问令牌：优先用「服务令牌」（state/agent-token，只有数据面权限）。
// MCP/agent 侧不再持有控制台令牌——否则该凭据一旦泄漏（prompt injection、日志等）就能
// 触达服务启停等控制面接口。
// 每次请求都重新读取，避免控制台轮换令牌后 MCP 仍用启动时的旧值导致一直 401。
function readBridgeToken() {
  try {
    const token = fs.readFileSync(path.join(APP_PATHS.stateDir, 'agent-token'), 'utf8').trim();
    if (token) return token;
  } catch {}
  try {
    const c = getConfig();
    if (c.agentToken) return String(c.agentToken);
  } catch {}
  // 兜底：老环境尚未生成 state/agent-token 时退回控制台令牌（桥接启动会自动创建前者）
  try {
    const c = getConfig();
    if (c.consoleToken) return String(c.consoleToken);
  } catch {}
  try {
    return fs.readFileSync(path.join(APP_PATHS.stateDir, 'console-token'), 'utf8').trim();
  } catch {
    return '';
  }
}

async function agentApi(path, init = {}) {
  const timeoutMs = init.timeoutMs || 15000;
  // 旧调用点把 query 直接拼在 path 里；这里拆开交给 data IPC 统一编码。
  const questionAt = String(path).indexOf('?');
  const rawPath = questionAt >= 0 ? String(path).slice(0, questionAt) : String(path);
  const query = questionAt >= 0 ? Object.fromEntries(new URLSearchParams(String(path).slice(questionAt + 1))) : undefined;
  const body = init.body !== undefined && init.body !== null ? JSON.parse(init.body) : undefined;
  const headers = init.headers ?? {};
  const res = await dataCall({
    method: String(init.method ?? (body !== undefined ? 'POST' : 'GET')).toUpperCase(),
    path: rawPath,
    query,
    body,
    token: readBridgeToken(),
    sessionToken: typeof headers['x-agent-token'] === 'string' ? headers['x-agent-token'] : undefined,
    timeoutMs
  });
  if (!res.ok) {
    throw new Error(res.json?.error || `桥接 API HTTP ${res.status}`);
  }
  return res.json;
}

async function authorizeRead(key, token) {
  await agentApi('/api/authorize/read', { method: 'POST', body: JSON.stringify({ key, token: token || undefined }) });
}

