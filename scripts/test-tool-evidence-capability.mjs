import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createCapabilityService } from '../src/capability/service.js';
import { createWorkspaceService } from '../src/workspace/service.js';
import { createTaskRuntime } from '../src/task/runtime.js';
import { createToolEvidenceStore, evidenceBinding } from '../src/context/tool-evidence.js';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'cetamesh-evidence-cap-'));
try {
 const stateDir = path.join(dir, 'state');
 const workspaceService = createWorkspaceService({ stateDir });
 const taskRuntime = createTaskRuntime({ stateDir });
 const evidenceStore = createToolEvidenceStore({ stateDir });
 const options = { stateDir, workspaceService, taskRuntime, evidenceStore };
 const service = createCapabilityService(options);
 assert.equal(service.broker.registry.has('context.evidence.read'), true, 'evidence retrieval must use existing Broker');
 const owner = { kind: 'owner', id: 'desktop' };
 const created = await service.broker.execute({ actor: owner, capability: 'workspace.create', approved: true,
  input: { root: path.join(dir, 'project'), createIfMissing: true, name: 'test' } });
 const workspaceId = created.result.workspace.id;
 fs.writeFileSync(path.join(dir, 'project', 'evidence.txt'), 'source');
 const task = taskRuntime.create({ goal: 'read evidence', workspaceId });
 let actor = service.grantTask(task.id, { capabilities: ['filesystem.read', 'context.evidence.read'] });
 const scope = { taskId: task.id, workspaceId };
 const binding = evidenceBinding({ actor, sessionId: 's1', scope });
 const ref = evidenceStore.put({ binding, content: 'preserved result', sourceCapability: 'filesystem.read', sourceInput: { path: 'evidence.txt' } });
 const request = (extra = {}) => ({ actor, ...scope, capability: 'context.evidence.read', input: { id: ref.id }, origin: { sessionId: 's1' }, ...extra });
 const result = await service.broker.execute(request());
 assert.equal(result.result.content, 'preserved result');
 await assert.rejects(service.broker.execute(request({ origin: { sessionId: 'foreign' } })), e => e.code === 'TOOL_EVIDENCE_DENIED');
 await assert.rejects(service.broker.execute(request({ origin: null })), e => e.code === 'TOOL_EVIDENCE_DENIED');
 await assert.rejects(service.broker.execute(request({ actor: { kind: 'extension', id: 'x', grants: actor.grants } })), e => e.code === 'PERMISSION_DENIED');
 actor = service.grantTask(task.id, { capabilities: ['context.evidence.read'] });
 await assert.rejects(service.broker.execute(request()), e => e.code === 'TOOL_EVIDENCE_DENIED');
 actor = service.grantTask(task.id, { capabilities: ['filesystem.read', 'context.evidence.read'] });
 const dangerous = evidenceStore.put({ binding, content: 'not for agent', sourceCapability: 'filesystem.read', sourceInput: { path: '../outside' } });
 await assert.rejects(service.broker.execute(request({ input: { id: dangerous.id } })), e => e.code === 'TOOL_EVIDENCE_DENIED');
 const unsupported = evidenceStore.put({ binding, content: 'private memory', sourceCapability: 'memory.read', sourceInput: {} });
 await assert.rejects(service.broker.execute(request({ input: { id: unsupported.id } })), e => e.code === 'TOOL_EVIDENCE_DENIED');
 const reloaded = createCapabilityService(options);
 assert.equal((await reloaded.broker.execute(request())).result.content, 'preserved result');
 const other = taskRuntime.create({ goal: 'legacy explicit grants', workspaceId });
 reloaded.grantTask(other.id, { capabilities: ['filesystem.read'] });
 const again = createCapabilityService(options);
 assert.equal(again.principalForTask(other.id).grants.capabilities.includes('context.evidence.read'), false, 'existing explicit grants must not migrate');
 taskRuntime.attachAgent({ id: task.id, expectedRev: taskRuntime.get({ id: task.id }).task.rev, provider: 'cetamesh', sessionId: 'replacement' });
 await assert.rejects(reloaded.broker.execute(request()),e=>e.code==='AGENT_ASSIGNMENT_EXPIRED');
 actor=reloaded.principalForTask(task.id);
 await assert.rejects(reloaded.broker.execute(request()), e => e.code === 'TOOL_EVIDENCE_DENIED');
 const ownerBinding = evidenceBinding({ actor: owner, sessionId: 'owner-chat' });
 const ownerRef = evidenceStore.put({ binding: ownerBinding, content: 'clock proof', sourceCapability: 'clock.now', sourceInput: {} });
 const ownerRead = await reloaded.broker.execute({ actor: owner, capability: 'context.evidence.read', input: { id: ownerRef.id }, origin: { sessionId: 'owner-chat' } });
 assert.equal(ownerRead.result.content, 'clock proof');
 console.log('tool evidence capability tests passed');
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
