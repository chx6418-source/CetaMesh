import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = fileURLToPath(new URL('../desktop-ui/', import.meta.url));
const require = createRequire(root + 'package.json');
const { createServer } = await import(pathToFileURL(require.resolve('vite')).href);
const vite = await createServer({ configFile: false, root, optimizeDeps: { noDiscovery: true }, server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
try {
  const { openReferenceTab, closeReferenceTab, clampPreviewWidth, PreviewLoadEpoch, PreviewWebHistory } = await vite.ssrLoadModule('/src/app/reference-viewer-state.ts');
  const webHistory = new PreviewWebHistory('https://example.com/');
  webHistory.record('https://example.com/second');
  assert.equal(webHistory.current, 'https://example.com/second', 'tab model retains actual navigation outside mounted child');
  assert.equal(webHistory.move(-1), 'https://example.com/');
  assert.equal(webHistory.move(1), 'https://example.com/second');
  webHistory.attach();
  webHistory.snapshot(['https://example.com/second'], 0);
  assert.equal(webHistory.canBack, true, 'recreating a child keeps the tab history');
  webHistory.move(-1); webHistory.attach();
  webHistory.snapshot(['https://example.com/'], 0);
  assert.equal(webHistory.canForward, true, 'restored child does not erase forward history');
  const scripted = new PreviewWebHistory('https://example.com/a'); scripted.attach();
  scripted.snapshot(['https://example.com/a', 'https://example.com/b', 'https://example.com/c'], 2);
  scripted.snapshot(['https://example.com/a', 'https://example.com/b', 'https://example.com/c'], 1);
  assert.equal(scripted.current, 'https://example.com/b'); assert.equal(scripted.canForward, true, 'native page initiated back is a traversal, not a new entry');
  const loads = new PreviewLoadEpoch();
  const old = loads.begin('a');
  const current = loads.begin('a');
  assert.equal(loads.isCurrent('a', old), false, 'a stale refresh cannot overwrite a later one');
  assert.equal(loads.isCurrent('a', current), true);
  loads.close('a');
  assert.equal(loads.isCurrent('a', current), false, 'a late file response cannot recreate a closed tab');
  const tab = id => ({ id, source: { kind: 'message', sessionId: 's1', messageId: 'm1', href: id } });
  let state = { tabs: [], activeId: '' };
  for (let i = 0; i < 8; i++) state = openReferenceTab(state.tabs, tab(String(i)));
  assert.equal(state.tabs.length, 8);
  const overflow = openReferenceTab(state.tabs, tab('overflow'));
  assert.equal(overflow.overflow, true); assert.equal(overflow.tabs, state.tabs);
  const duplicate = openReferenceTab(state.tabs, { ...tab('2'), id: 'not-added' });
  assert.equal(duplicate.activeId, '2'); assert.equal(duplicate.tabs.length, 8);
  const differentScope = { ...tab('2'), source: { ...tab('2').source, sessionId: 'another' } };
  assert.equal(openReferenceTab([tab('2')], differentScope).tabs.length, 2);
  assert.equal(closeReferenceTab(state.tabs, '3', '3').activeId, '2');
  assert.equal(closeReferenceTab([tab('1')], '1', '1').activeId, '');
  assert.equal(clampPreviewWidth(100, 1200), 320);
  assert.equal(clampPreviewWidth(2000, 1000), 600);
  assert.ok(clampPreviewWidth(500, 644) <= 324);
  console.log('PASS tab identity/scope, deduplication, resource limit, deterministic close and constrained dock width');
} finally { await vite.close(); }
