import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { inspectDshPreset, createDshPresetPolicy } from '../src/agent/dsh-preset-policy.js';
import { createDshConfiguration } from '../src/agent/dsh-configuration.js';
import { createDshCoreConnector } from '../src/agent/dsh-core-connector.js';
import { createDshAgentProvider } from '../src/agent/dsh-agent-provider.js';
import { createAgentService } from '../src/agent/service.js';
import { createAgentProviderRegistry } from '../src/agent/registry.js';
import { createAgentBroker } from '../src/agent/broker.js';
import { createDesktopUiService } from '../src/desktop/ui-service.js';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cetamesh-dsh-setup-'));
const home = path.join(root, 'home');
const stateDir = path.join(root, 'state');
fs.mkdirSync(stateDir, { recursive: true });
const preset = (id, text) => {
  const dir = path.join(home, '.agent-presets', id);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'agent.cordis.yml'), text);
};
const valid = prefix => `- id: "persona"\n  name: '@deepseek-ai/dsh-persona'\n  config:\n    prefix: ${prefix}\n`;
try {
  preset('coding-a', '\uFEFF# comment\n' + valid('|-\n      safe synthetic persona'));
  preset('coding-b', valid('"another synthetic persona"'));
  preset('social', valid('"social synthetic persona"'));
  assert.equal(inspectDshPreset({ id: 'coding-a', dshHome: home }).compatible, true);
  preset('empty', valid('>-'));
  assert.equal(inspectDshPreset({ id: 'empty', dshHome: home }).reason, 'persona-prefix-required');
  preset('decoy', '- id: persona\n  name: wrong-package\n  config:\n    prefix: safe\n');
  assert.equal(inspectDshPreset({ id: 'decoy', dshHome: home }).reason, 'preset-schema-unverified');
  preset('misplaced', '- id: persona\n  name: "@deepseek-ai/dsh-persona"\n  prefix: safe\n  config: {}\n');
  assert.equal(inspectDshPreset({ id: 'misplaced', dshHome: home }).reason, 'persona-prefix-required');
  preset('alias', '- &p { id: persona, name: "@deepseek-ai/dsh-persona", config: { prefix: safe } }\n- *p\n');
  assert.equal(inspectDshPreset({ id: 'alias', dshHome: home }).reason, 'preset-yaml-limits-exceeded');
  preset('big', '#'.repeat(256 * 1024 + 1));
  assert.equal(inspectDshPreset({ id: 'big', dshHome: home }).reason, 'preset-file-too-large');
  preset('deep', 'x: '.repeat(60) + 'true');
  assert.equal(inspectDshPreset({ id: 'deep', dshHome: home }).compatible, false);
  assert.equal(inspectDshPreset({ id: '../escape', dshHome: home }).reason, 'preset-not-configured');

  preset('broken', '- id: persona\n  name: [broken\n');
  assert.equal(inspectDshPreset({ id: 'broken', dshHome: home }).reason, 'preset-yaml-invalid');
  const outside = path.join(root, 'outside');
  fs.mkdirSync(outside); fs.writeFileSync(path.join(outside, 'agent.cordis.yml'), valid('safe'));
  const linked = path.join(home, '.agent-presets', 'linked');
  fs.symlinkSync(outside, linked, process.platform === 'win32' ? 'junction' : 'dir');
  assert.equal(inspectDshPreset({ id: 'linked', dshHome: home }).reason, 'preset-path-outside-root');

  const config = createDshConfiguration({ legacy: { homeDir: home, codingPreset: 'coding-a', socialPreset: 'social', authCookie: 'never-export-me' }, stateDir, configFile: path.join(root, 'config.json'), dataRoot: root, env: {} });
  assert.equal(config.describe().source, 'legacy-config');
  const unavailableLegacy = createDshConfiguration({ legacyLoadError: 'LEGACY_CONFIG_UNAVAILABLE', env: {} });
  assert.equal(unavailableLegacy.describe().loadError, 'LEGACY_CONFIG_UNAVAILABLE');
  assert.equal(config.active.codingPreset, 'coding-a');
  assert.throws(() => config.configure({ homeDir: home, baseUrl: 'https://other-dsh.invalid', codingPreset: 'coding-a' }), error => error.code === 'DSH_AUTH_SCOPE_CHANGE_REQUIRES_REVIEW');
  const before = fs.readFileSync(path.join(home, '.agent-presets/coding-a/agent.cordis.yml'));
  assert.throws(() => config.configure({ homeDir: home, codingPreset: 'empty' }), error => error.code === 'DSH_PRESET_INCOMPATIBLE');
  assert.equal(config.describe().revision, 0);
  const result = config.configure({ homeDir: home, codingPreset: 'coding-b', socialPreset: 'social' });
  assert.equal(result.applied, false); assert.equal(result.restartRequired, true);
  assert.equal(config.active.codingPreset, 'coding-a', 'live generation stays pinned');
  assert.equal(config.describe().pending.codingPreset, 'coding-b');
  assert.equal(config.describe().source, 'legacy-config', 'active source does not change on deferred save');
  assert.equal(config.describe().pendingConfigFile, path.join(stateDir, 'dsh-connector.json'));
  const blockedState = path.join(root, 'blocked-state');
  fs.mkdirSync(path.join(blockedState, 'dsh-connector.json'), { recursive: true });
  const writeFailure = createDshConfiguration({ stateDir: blockedState, env: {} });
  assert.throws(() => writeFailure.configure({ homeDir: home, codingPreset: 'coding-a' }), error => error.code === 'DSH_CONFIG_WRITE_FAILED');
  assert.equal(writeFailure.describe().restartRequired, false, 'failed persistence never claims pending success');
  const restarted = createDshConfiguration({ legacy: { codingPreset: 'coding-a' }, stateDir, env: {} });
  assert.equal(restarted.active.codingPreset, 'coding-b');
  assert.equal(restarted.describe().activeRevision, 1);
  assert.equal(restarted.describe().restartRequired, false);
  assert.deepEqual(fs.readFileSync(path.join(home, '.agent-presets/coding-a/agent.cordis.yml')), before);
  assert.equal(JSON.stringify(config.describe()).includes('never-export-me'), false);
  assert.equal(JSON.stringify(fs.readFileSync(path.join(stateDir, 'dsh-connector.json'), 'utf8')).includes('never-export-me'), false);
  const productOnly = createDshCoreConnector({ config: { agents: { defaultAgentPreset: 'social' }, dsh: { homeDir: home } }, env: {} });
  assert.equal(productOnly.presetConfig.coding, null, 'product default never silently becomes the coding execution preset');
  const connector = createDshCoreConnector({ config: { dsh: { codingPreset: 'coding-a' } }, stateDir, env: {} });
  assert.equal(connector.presetConfig.coding, 'coding-b', 'versioned source overrides legacy');

  let listMode = 'loaded';
  let firstError = null;
  const calls = [];
  const api = { async callEndpoint(endpoint, args) {
    calls.push({ endpoint, args });
    if (firstError) throw Object.assign(new Error('secret transport detail'), { code: firstError });
    if (endpoint === 'agentPresets/list') {
      if (listMode === 'timeout') throw Object.assign(new Error('never expose token'), { code: 'DSH_REQUEST_TIMEOUT' });
      if (listMode === 'auth') throw Object.assign(new Error('expired'), { code: 'DSH_AUTHENTICATION_FAILED' });
      return listMode === 'malformed' ? {} : { presets: listMode === 'loaded' ? [{ id: 'coding-a' }] : [] };
    }
    if (endpoint === 'session/create') return { sessionId: 'synthetic-session' };
    return {};
  }, async *openRemoteStream() {} };
  const provider = createDshAgentProvider({ api, defaults: { model: null }, presetPolicy: createDshPresetPolicy({ coding: 'coding-a', dshHome: home }) });
  assert.equal((await provider.health()).ready, true);
  listMode = 'absent';
  assert.equal((await provider.health()).preset.loaded, false);
  listMode = 'timeout';
  const timeout = await provider.health();
  assert.equal(timeout.reason, 'preset-load-unknown'); assert.equal(timeout.preset.loaded, null);
  assert.equal(timeout.authenticated, null); assert.equal(timeout.diagnostic.retryable, true);
  assert.equal(timeout.diagnostic.stage, 'native-loading');
  assert.equal(JSON.stringify(timeout).includes('never expose'), false);
  listMode = 'auth'; assert.equal((await provider.health()).authenticated, false);
  listMode = 'malformed'; assert.equal((await provider.health()).preset.loadState, 'unknown');
  for (const [error, reason] of [['DSH_AUTH_MATERIAL_MISSING', 'authentication-material-missing'], ['DSH_AUTHENTICATION_FAILED', 'authentication-required'], ['DSH_UNREACHABLE', 'not_connected']]) {
    firstError = error; assert.equal((await provider.health()).reason, reason);
  }
  firstError = null; listMode = 'loaded';
  const registry = createAgentProviderRegistry({ providers: [provider] });
  const broker = createAgentBroker({ registry });
  const service = createAgentService({ broker, dshConfiguration: config });
  const ui = createDesktopUiService({ services: { agentService: service } });
  const call = (method, params = {}) => ui.execute({ method, params });
  const listed = (await call('ui.agent.list')).agents[0];
  const checked = await call('ui.agent.health', { provider: 'dsh' });
  assert.deepEqual({ ...listed, diagnostic: null }, { ...checked, diagnostic: null }, 'list/health share identity, auth and capability projection');
  assert.equal(checked.configured, true); assert.equal(checked.ready, true);
  assert.equal(checked.configuration.active.codingPreset, 'coding-a');
  assert.equal(JSON.stringify(checked).includes('never-export-me'), false);
  const saved = await call('ui.agent.configure', { agentId: 'dsh', config: { homeDir: home, codingPreset: 'coding-b', socialPreset: 'social' } });
  assert.equal(saved.restartRequired, true); assert.equal(saved.applied, false);
  await assert.rejects(() => call('ui.agent.configure', { agentId: 'dsh', config: [] }), error => error.code === 'INVALID_PARAMS');
  const partial = config.configure({ socialPreset: null });
  assert.equal(partial.configuration.pending.codingPreset, 'coding-b', 'partial updates retain the coding selection');
  assert.equal(partial.configuration.pending.socialPreset, null);
  await provider.createSession({ purpose: 'coding' });
  assert.equal(calls.find(c => c.endpoint === 'session/create').args.request.agentPreset, 'coding-a', 'session creation retains original generation after save');
  const snap = { provider: 'dsh', available: true, authenticated: true, compatible: true, configured: true, ready: true, sessionCapable: true, taskEligible: true, workspaceBoundary: 'capability-broker', status: 'available' };
  const flatUi = createDesktopUiService({ services: { agentService: { execute: ({ method }) => method === 'agent.list' ? { providers: [{ id: 'dsh', ...snap, health: snap }] } : snap } } });
  assert.deepEqual((await flatUi.execute({ method: 'ui.agent.list' })).agents[0], await flatUi.execute({ method: 'ui.agent.health', params: { provider: 'dsh' } }), 'flat and nested inputs preserve the same fields');
  const unknownUi = createDesktopUiService({ services: { agentService: { execute: () => ({ provider: 'dsh' }) } } });
  const unknown = await unknownUi.execute({ method: 'ui.agent.health', params: { provider: 'dsh' } });
  assert.equal(unknown.authenticated, null); assert.equal(unknown.configured, null); assert.equal(unknown.ready, null); assert.equal(unknown.taskEligible, null); assert.equal(unknown.available, null);
  service.close();
  fs.writeFileSync(path.join(stateDir, 'dsh-connector.json'), '{broken');
  const corrupt = createDshConfiguration({ legacy: { codingPreset: 'coding-a' }, stateDir });
  assert.equal(corrupt.describe().loadError, 'DSH_CONFIG_INVALID');
  assert.equal(corrupt.active.codingPreset, null, 'corrupt override never silently falls back to stale executable selection');
  console.log('DSH setup: production parser, configuration generation, native discovery and Owner DTO contracts PASS');
} finally { fs.rmSync(root, { recursive: true, force: true }); }
